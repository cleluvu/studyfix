// Behavioral navigation tests with mocked HTTP/media/DOM; not real browser E2E.
import assert from "node:assert/strict";
let checks=0;
const check=(condition,message)=>{assert.ok(condition,message);checks++;};
const storage=new Map();
globalThis.sessionStorage={getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value),removeItem:key=>storage.delete(key)};
globalThis.setTimeout=()=>1;
const root={innerHTML:""},toasts={appendChild(){}};
globalThis.document={title:"StudyFix",activeElement:null,querySelector:s=>s==="#app"?root:s==="#toast-region"?toasts:null,querySelectorAll:()=>[],getElementById:()=>null,addEventListener(){},createElement:()=>({innerHTML:"",remove(){}})};
const {state,rememberView,restoreView}=await import("../static/core/state.js");
const {layout,renderRoomListCompact}=await import("../static/ui/render.js");
const {leaveMeeting,leaveRoomMembership}=await import("../static/features/room/room.js");
const {navigate,loadCurrentRoom}=await import("../static/core/polling.js");
const {receiveScreenSignal}=await import("../static/features/screen-share/screen-share.js");
const identity={userId:"teacher",role:"TEACHER",displayName:"Teacher"};
const room={roomId:"6",roomCode:"Java A",version:0,code:"code",members:[],history:[]};
let serverRoom=room,requests=[],delayCurrent=false,completeOldCurrent;
const response=(payload,status=200)=>({ok:status<400,status,json:async()=>payload});
globalThis.fetch=async(path,options={})=>{
  const body=options.body?JSON.parse(options.body):null;requests.push({path,body});
  if(path==="/api/rooms/current"&&delayCurrent){delayCurrent=false;return new Promise(resolve=>{completeOldCurrent=resolve;});}
  if(path==="/api/rooms/current")return serverRoom?response({room:serverRoom}):response({message:"Bạn chưa vào phòng"},409);
  if(path==="/api/rooms/current/command"&&body.action==="LEAVE_ROOM"){serverRoom=null;return response({ok:true,leftRoomId:"6"});}
  if(path==="/api/me")return response({identity,peerId:"peer",roomId:serverRoom?.roomId||""});
  if(path.startsWith("/api/rooms?"))return response({rooms:[{...room,memberCount:serverRoom?1:0,isMine:true}],total:1,page:1,totalPages:1,customRoomCodes:true,manualRoomDelete:true});
  if(path==="/api/assignments")return response({status:"OK",data:{assignments:[]}});
  if(path==="/api/classroom")return response({classroom:{phase:"WAITING",round:0,master:{code:"code",version:0},branches:[],events:[],chat:[]}});
  return response({ok:true,messages:[],latestId:0,unreadCount:0});
};
state.identity=identity;state.token="token";state.room=room;state.roomId="6";state.page="room";state.booting=true;
rememberView();state.page="overview";
check(restoreView()==="room","refresh restores meeting after membership is confirmed");
const saved=storage.get("studyfix.web.view");
state.room=null;check(restoreView()==="overview","refresh cannot open meeting after membership is lost");
state.room=room;state.identity={...identity,userId:"other"};
check(restoreView()==="overview","saved meeting cannot leak to another account");
state.identity=identity;state.page="room";storage.set("studyfix.web.view",saved);
let callStopped=0,screenStopped=0;
state.callJoined=true;state.callLocal={getTracks:()=>[{stop(){callStopped++;}}]};
state.screenActive=true;state.localStream={getTracks:()=>[{stop(){screenStopped++;}}]};
await leaveMeeting();
check(state.page==="overview"&&state.room?.roomId==="6"&&state.roomId==="6","leave meeting returns home and preserves membership");
check(!state.callJoined&&!state.screenActive&&callStopped===1&&screenStopped===1,"leave meeting releases call and capture tracks");
check(requests.some(r=>r.path==="/api/call/signal"&&r.body.kind==="LEAVE")&&requests.some(r=>r.path==="/api/screen/signal"&&r.body.kind==="END"),"leave meeting notifies call and screen signaling");
check(!requests.some(r=>r.body?.action==="LEAVE_ROOM"),"leave meeting never sends membership leave");
check(restoreView()==="overview","refresh after leaving meeting remains home");
const main=layout("");
check(!main.match(/class="nav-btn[^>]*data-page="room"/),"home sidebar does not acquire a room item from membership");
check(renderRoomListCompact().includes('data-action="leave-room"'),"home room directory offers explicit membership leave");
await receiveScreenSignal({kind:"ACTIVE",fromPeerId:"other",roomId:"6"});
check(!state.screenActive&&!state.remoteStream&&!state.activeScreenPresenterId,"incoming screen presence cannot reopen media after leaving meeting");
await navigate("room");
check(state.page==="room"&&!state.meetingClosed,"entering current room reopens meeting without joining membership again");
check(restoreView()==="room","reentered meeting is restored on refresh");
delayCurrent=true;const oldPoll=loadCurrentRoom(false);
await leaveRoomMembership("6");
completeOldCurrent(response({room}));await oldPoll;
check(!state.room&&state.roomId===""&&state.page==="overview","explicit membership leave survives a late old room response");
check(requests.filter(r=>r.body?.action==="LEAVE_ROOM").length===1,"only explicit membership leave sends LEAVE_ROOM");
check(!state.roomLeaving&&state.token==="token","leave finishes cleanly without logging out");
check(restoreView()==="overview","refresh after membership leave stays home");
const before=requests.length;await leaveRoomMembership("6");
check(requests.length===before,"stale leave button cannot leave a different or absent room");
check(!renderRoomListCompact().includes('data-action="leave-room"'),"leave control disappears after membership leave");
console.log(`Meeting navigation: ${checks} checks PASS (mock HTTP/media/DOM).`);
